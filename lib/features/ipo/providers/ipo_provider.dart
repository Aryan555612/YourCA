final filteredIpoListProvider = Provider<List<IpoItem>>((ref) {
  final allIpos = ref.watch(rawIpoListProvider);
  final category = ref.watch(selectedIpoCategoryProvider);
  final status = ref.watch(selectedIpoStatusProvider);
  final search = ref.watch(ipoSearchQueryProvider).trim().toLowerCase();
  final bookmarkedIds = ref.watch(bookmarkedIpoIdsProvider);

  return allIpos.map((ipo) => ipo.copyWith(isBookmarked: bookmarkedIds.contains(ipo.id))).where((ipo) {
    if (category != null && ipo.category != category) return false;
    if (status != null && ipo.status != status) return false;
    if (search.isNotEmpty) {
      final matchesName = ipo.name.toLowerCase().contains(search);
      final matchesSymbol = ipo.symbol.toLowerCase().contains(search);
      final matchesSector = ipo.sector.toLowerCase().contains(search);
      if (!matchesName && !matchesSymbol && !matchesSector) return false;
    }
    return true;
  }).toList();
});
